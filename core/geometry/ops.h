#pragma once
// Объединение и разрезание объектов (группа инструментов «Объединение»).
#include "core/geometry/entity.h"
#include <optional>
#include <vector>

namespace psi {

// Соединить линии / дуги / разомкнутые полилинии с совпадающими концами в одну полилинию
// (дуги становятся сегментами с bulge). Замкнута, если концы цепочки сходятся. nullopt, если
// цепочка не единая (есть куски, не примыкающие к остальным) или вход пуст.
std::optional<Entity> joinEntities(const std::vector<Entity>& parts, double tol = 1e-6);

// Разрезать объект в точке `at` (берётся ближайшая точка на объекте). Линия / дуга / разомкнутая
// полилиния / сплайн / дуга эллипса → две части; окружность, замкнутая полилиния, замкнутый
// сплайн → один разомкнутый объект, начинающийся и заканчивающийся в точке разреза.
// Пусто, если объект нельзя разрезать (текст, размер, штриховка) или точка совпадает с концом.
std::vector<Entity> splitEntity(const Entity& e, Point at);

// Разрезать `e` во всех точках пересечения с `cutter`. Пусто, если пересечений нет.
std::vector<Entity> cutEntity(const Entity& e, const Entity& cutter);

// Разрезать `e` в нескольких точках (лежащих на объекте). Пусто, если ни одна точка не режет.
std::vector<Entity> splitEntityAt(const Entity& e, const std::vector<Point>& at);

} // namespace psi
